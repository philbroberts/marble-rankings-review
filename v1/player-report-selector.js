const controls = document.querySelector('#player-report-controls');
const team = controls.querySelector('#player-report-team');
const season = controls.querySelector('#player-report-season');
const current = controls.dataset;
for (const name of [...new Set(reports.map(report => report.team))].sort((a,b) => a === 'National' ? -1 : b === 'National' ? 1 : a.localeCompare(b))) {
  team.add(new Option(name, name));
}
team.value = current.team;
function setSeasons(preferred) {
  const options = reports.filter(report => report.team === team.value);
  season.replaceChildren(...options.map(report => {
    const end = Number(report.season);
    return new Option(String(end - 1) + '\u2013' + report.season.slice(-2), report.season);
  }));
  season.value = options.some(report => report.season === preferred)
    ? preferred : options.at(-1).season;
}
function openReport() {
  const report = reports.find(item => item.team === team.value && item.season === season.value);
  if (report && (report.team !== current.team || report.season !== current.season)) {
    window.location.href = current.root + report.path;
  }
}
setSeasons(current.season);
team.addEventListener('change', () => {
  setSeasons(season.value);
  openReport();
});
season.addEventListener('change', openReport);
